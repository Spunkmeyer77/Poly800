"""Generate plugin/Source/FactoryPrograms.h from the canonical factory CSVs."""
import csv
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[2]
verified = root / "factory" / "poly800-mk1-verified.csv"
catalog = root / "factory" / "poly800-mk1-catalog.csv"
out = root / "plugin" / "Source" / "FactoryPrograms.h"

names = {r["program"]: r["name"] for r in csv.DictReader(catalog.open())}
rows = list(csv.DictReader(verified.open()))
cols = [c for c in rows[0].keys() if c != "program"]

lines = [
    "// SPDX-License-Identifier: GPL-3.0-or-later",
    "// Generated by plugin/tools/gen_factory_header.py - do not edit.",
    "#pragma once",
    "",
    "namespace factory",
    "{",
    f"constexpr int numParams = {len(cols)};",
    "constexpr int paramNumbers[numParams] = { " + ", ".join(c[1:] for c in cols) + " };",
    "",
    "struct Program { int number; const char* name; int values[numParams]; };",
    "",
    f"constexpr int numPrograms = {len(rows)};",
    "constexpr Program programs[numPrograms] = {",
]
for r in rows:
    name = names.get(r["program"], "Program " + r["program"]).replace('"', '\\"')
    vals = ", ".join(r[c] for c in cols)
    lines.append(f'    {{ {r["program"]}, "{name}", {{ {vals} }} }},')
lines += ["};", "} // namespace factory", ""]
out.write_text("\n".join(lines))
print(f"wrote {out} ({len(rows)} programs, {len(cols)} params)", file=sys.stderr)
